"""
Глобальна конфігурація лабораторної роботи.

Усі гіперпараметри зібрані в одному місці, щоб експерименти були відтворюваними,
а у звіті можна було просто послатися на цей файл.

ВАЖЛИВО щодо ресурсів: на комп'ютері мало вільного місця на диску та обмежена RAM,
тому:
  * вихідний датасет (~11 ГБ) НЕ копіюється і НЕ розпаковується повністю;
  * використовується лише підвибірка зображень, які один раз зменшуються до 320 px
    і зберігаються у стиснутому JPEG-вигляді в одному невеликому файлі-кеші (~десятки МБ);
  * ваги моделей на диск не зберігаються (лише метрики у JSON та графіки PNG).
"""
from pathlib import Path

# ----------------------------------------------------------------------------------
# Шляхи
# ----------------------------------------------------------------------------------
PROJECT_ROOT = Path(__file__).resolve().parent.parent
DATASET_DIR = PROJECT_ROOT / "ArTaxOr"                 # оригінальний датасет (тільки читання)
CACHE_DIR = PROJECT_ROOT / "data"                      # компактний кеш зменшених зображень
CACHE_FILE = CACHE_DIR / "artaxor_320.pkl"             # єдиний файл кешу
RESULTS_DIR = PROJECT_ROOT / "results"                 # метрики (JSON) та графіки (PNG)
FIGURES_DIR = RESULTS_DIR / "figures"
LOGS_DIR = RESULTS_DIR / "logs"

# ----------------------------------------------------------------------------------
# Дані
# ----------------------------------------------------------------------------------
# 7 таксономічних рядів членистоногих. Індекс 0 у Faster R-CNN зарезервовано під фон,
# тому класи нумеруються з 1.
CLASSES = [
    "Araneae",      # павуки
    "Coleoptera",   # жуки
    "Diptera",      # двокрилі (мухи, комарі)
    "Hemiptera",    # напівтвердокрилі (клопи, попелиці, цикади)
    "Hymenoptera",  # перетинчастокрилі (мурахи, бджоли, оси)
    "Lepidoptera",  # лускокрилі (метелики)
    "Odonata",      # бабки
]
NUM_CLASSES = len(CLASSES) + 1  # +1 клас «фон»

IMAGE_SIZE = 320            # довша сторона зображення після зменшення (px)
JPEG_QUALITY = 90           # якість стиснення зображень у кеші
TRAIN_PER_CLASS = 100       # скільки зображень кожного класу йде у федеративне навчання
TEST_PER_CLASS = 30         # скільки зображень кожного класу у спільному тестовому наборі сервера
MIN_BOX_SIZE = 4            # рамки, менші за 4 px після зменшення, відкидаються

SEED = 42

# ----------------------------------------------------------------------------------
# Модель та локальне навчання (на стороні клієнта)
# ----------------------------------------------------------------------------------
TRAINABLE_BACKBONE_LAYERS = 0   # backbone MobileNetV3 заморожено (fine-tuning FPN + RPN + голови)
BATCH_SIZE = 8
LOCAL_EPOCHS = 1                # кількість локальних епох за один раунд
CLIENT_LR = 0.01                # швидкість навчання SGD на клієнті
CLIENT_MOMENTUM = 0.9
CLIENT_WEIGHT_DECAY = 1e-4

# ----------------------------------------------------------------------------------
# Федеративне навчання
# ----------------------------------------------------------------------------------
NUM_CLIENTS = 2                 # за умовою: набір розбивається на ДВІ частини
NUM_ROUNDS = 10                 # кількість комунікаційних раундів

# FedProx: коефіцієнт проксимального члена  (mu / 2) * ||w - w_global||^2
FEDPROX_MU = 0.1

# FedAdam (Reddi et al., 2021, "Adaptive Federated Optimization"):
FEDADAM_ETA = 1e-2              # серверна швидкість навчання (підібрано tune_fedadam.py)
FEDADAM_BETA1 = 0.9
FEDADAM_BETA2 = 0.99
FEDADAM_TAU = 1e-3              # параметр адаптивності (запобігає діленню на ~0)

STRATEGIES = ["fedavg", "fedadam", "fedprox"]
SCENARIOS = ["iid_equal", "unequal_balanced", "unequal_imbalanced", "missing_classes"]
